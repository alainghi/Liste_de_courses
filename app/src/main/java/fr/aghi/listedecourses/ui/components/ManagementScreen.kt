@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun ManagementScreen(navController: NavController) {
    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text("Gestion") },
                navigationIcon = {
                    IconButton(onClick = { navController.popBackStack() }) {
                        Icon(Icons.AutoMirrored.Filled.ArrowBack, contentDescription = "Retour")
                    }
                }
            )
        }
    ) { innerPadding ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(innerPadding)
                .padding(16.dp),
            horizontalAlignment = Alignment.CenterHorizontally,
            verticalArrangement = Arrangement.Center
        ) {
            Button(onClick = { navController.navigate("category_management") }) {
                Text("Gérer les catégories")
            }
            Spacer(modifier = Modifier.height(16.dp))
            Button(onClick = { navController.navigate("product_management") }) {
                Text("Gérer les articles")
            }
        }
    }
}